import { PRINT_CADUCEUS_DATA_URI, PRINT_BRAND_HEADER_DATA_URI } from "./printBrand";
import { CLINIC_CONFIG } from "./clinicConfig";
import { formatDateOnlyIST, formatTimeIST } from "./format";

