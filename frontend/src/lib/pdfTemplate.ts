export type PdfHeaderOptions = {
  title?: string;
  subtitle?: string;
  printDate?: string;
  printTime?: string;
  generatedBy?: string;
};

/**
 * Standard Ayu Polyclinic PDF Header (Reference Image 1)
 * Displays:
 *  - Blue medical cross logo with stylized silhouettes on left
 *  - Vertical grey separator line
 *  - Large bold "AYU" in primary blue (#1e567a)
 *  - Bold "POLYCLINIC" in grey (#808080)
 *  - Solid horizontal blue divider line across full width
 *  - Optional report title section below the divider
 */
export function renderAyuPdfHeaderHtml(options?: PdfHeaderOptions): string {
  const now = new Date();
  const printDate = options?.printDate || now.toLocaleDateString("en-GB");
  const printTime =
    options?.printTime ||
    now.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: true });
  const generatedBy = options?.generatedBy || "Ayu Polyclinic System";

  const titleSection = options?.title
    ? `<div class="ayu-shared-title-row" style="display:flex;justify-content:space-between;align-items:flex-end;gap:16px;margin:12px 0 16px;font-family:Arial,Helvetica,sans-serif;">
        <div><h1 style="margin:0 0 4px;font-size:18px;line-height:1.2;font-weight:800;color:#1d4289;">${escapeHtml(options.title)}</h1>
          ${options.subtitle ? `<p style="margin:0;font-size:11px;color:#334155;">${escapeHtml(options.subtitle)}</p>` : ""}</div>
        <div style="text-align:right;font-size:8px;color:#334155;line-height:1.45;white-space:nowrap;">
          <div>Print Date: <strong>${escapeHtml(printDate)}</strong></div>
          <div>Generated By: <strong>${escapeHtml(generatedBy)}</strong></div>
          <div>Generated Time: <strong>${escapeHtml(printTime)}</strong></div>
        </div>
      </div>`
    : "";

  return `
    <div class="ayu-shared-header-shell" style="width:100%;font-family:Arial,Helvetica,sans-serif;box-sizing:border-box;margin-bottom:12px;color:#1d4289;">
      <div class="ayu-shared-brand-bar" style="display:flex;align-items:flex-start;justify-content:space-between;gap:16px;min-height:82px;padding-bottom:6px;">
        <div style="display:flex;flex-direction:column;align-items:flex-start;">
          <div style="display:inline-block;margin:0 0 5px;border-bottom:2px solid #1d4289;padding-bottom:2px;font-size:26px;font-weight:900;line-height:1.1;color:#1d4289;">AYU POLYCLINIC</div>
          <div style="font-size:16px;font-weight:800;line-height:1.2;color:#1d4289;">Dr. Sushanth. B</div>
          <div style="margin-top:2px;font-size:11px;font-weight:700;line-height:1.25;color:#1d4289;">MBBS (Gandhi), (FCCM)</div>
          <div style="font-size:11px;font-weight:700;line-height:1.25;color:#1d4289;">TSMC/FM/27444</div>
        </div>
        <img src="${PRINT_CADUCEUS_DATA_URI}" alt="Blue medical caduceus" style="width:78px;height:76px;object-fit:contain;object-position:center top;display:block;flex:0 0 auto;" />
      </div>
      ${titleSection}
    </div>
  `;
}

