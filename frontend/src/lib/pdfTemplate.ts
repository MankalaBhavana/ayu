/**
 * Centralized Ayu Polyclinic PDF & Print Header/Footer Template
 * Reproduces Reference Images 1 and 2 identically across all modules.
 */
import { PRINT_BRAND_HEADER_DATA_URI, PRINT_MEDICAL_SYMBOL_DATA_URI } from "./printBrand";

export const AYU_PDF_COLORS = {
  primary: "#1e567a",
  subtitle: "#808080",
  divider: "#b4b4b4",
  text: "#0f172a",
  background: "#ffffff",
};

export type PdfHeaderOptions = {
  title?: string;
  subtitle?: string;
  printDate?: string;
  printTime?: string;
  generatedBy?: string;
};

/**
 * Standard Ayu Polyclinic PDF Header (Reference Image 1)
 * Displays:
 *  - Blue medical cross logo with stylized silhouettes on left
 *  - Vertical grey separator line
 *  - Large bold "AYU" in primary blue (#1e567a)
 *  - Bold "POLYCLINIC" in grey (#808080)
 *  - Solid horizontal blue divider line across full width
 *  - Optional report title section below the divider
 */
export function renderAyuPdfHeaderHtml(options?: PdfHeaderOptions): string {
  const now = new Date();
  const printDate = options?.printDate || now.toLocaleDateString("en-GB");
  const printTime =
    options?.printTime ||
    now.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: true });
  const generatedBy = options?.generatedBy || "Ayu Polyclinic System";

  const titleSection = options?.title
    ? `
      <div class="ayu-shared-title-row" style="display: flex; justify-content: space-between; align-items: flex-end; margin-top: 14px; margin-bottom: 16px;">
        <div>
          <h1 style="margin: 0 0 4px; font-size: 20px; font-weight: 800; color: #0f172a;">${escapeHtml(options.title)}</h1>
          ${options.subtitle ? `<p style="margin: 0; font-size: 13px; color: #475569;">${escapeHtml(options.subtitle)}</p>` : `<p style="margin: 0; font-size: 13px; color: #475569;">AYU POLYCLINIC | Diagnostics | Pharmacy</p>`}
        </div>
        <div style="text-align: right; font-size: 11.5px; color: #334155; line-height: 1.5;">
          <div><span>Print Date: </span><strong>${printDate}</strong></div>
          <div><span>Generated By: </span><strong>${escapeHtml(generatedBy)}</strong></div>
          <div><span>Generated Time: </span><strong>${printTime}</strong></div>
        </div>
      </div>
    `
    : "";

  return `
    <div class="ayu-shared-header-shell" style="width: 100%; font-family: Arial, Helvetica, sans-serif; box-sizing: border-box; margin-bottom: 12px;">
      <div class="ayu-shared-brand-bar" style="display: flex; align-items: center; justify-content: flex-start; gap: 0; padding-bottom: 8px;">
        <div style="flex-shrink: 0; display: flex; align-items: center;">
          <img src="${PRINT_BRAND_HEADER_DATA_URI}" alt="AYU POLYCLINIC Logo" style="height: 68px; width: auto; max-width: 80px; object-fit: contain; display: block;" />
        </div>
        <div style="width: 1px; height: 56px; background-color: #b4b4b4; margin: 0 16px; flex-shrink: 0;"></div>
        <div style="display: flex; flex-direction: column; justify-content: center;">
          <div style="font-size: 34px; font-weight: 800; color: #1e567a; line-height: 1.05; letter-spacing: 0.5px;">AYU</div>
          <div style="font-size: 15px; font-weight: 700; color: #808080; line-height: 1.15; letter-spacing: 0.4px; margin-top: 4px;">POLYCLINIC</div>
        </div>
      </div>
      <div class="ayu-shared-header-rule" style="width: 100%; height: 0; border-top: 3.5px solid #1e567a; margin-top: 4px;"></div>
      ${titleSection}
    </div>
  `;
}

